#!/usr/bin/env bash
# Regenerates apps-script/Logo.js from bakehouse.png (Apps Script can't serve
# repo files, so the logo is embedded as a data URI). Requires ImageMagick.
set -euo pipefail
cd "$(dirname "$0")/.."
tmp=$(mktemp --suffix=.png)
magick bakehouse.png -resize 360x -strip -colors 48 -define png:compression-level=9 "$tmp"
{
  echo '// Generated by tools/build-logo.sh — do not edit.'
  printf "const LOGO_DATA_URI = 'data:image/png;base64,%s';\n" "$(base64 -w0 "$tmp")"
} > apps-script/Logo.js
rm "$tmp"
echo "Wrote apps-script/Logo.js ($(wc -c < apps-script/Logo.js) bytes)"
